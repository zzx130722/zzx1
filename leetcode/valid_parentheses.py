"""
LeetCode 20. 有效的括号（Valid Parentheses）—— 难度：简单
https://leetcode.cn/problems/valid-parentheses/

题目
----
给定一个只包括 '('，')'，'{'，'}'，'['，']' 的字符串 s，判断字符串是否有效。

有效字符串需满足：
    1. 左括号必须用相同类型的右括号闭合。
    2. 左括号必须以正确的顺序闭合。
    3. 每个右括号都有一个对应的相同类型的左括号。

--------------------------------------------------------------------------
思路：栈（后进先出）
--------------------------------------------------------------------------
为什么是栈？因为括号的嵌套规则本身就是"后开的先关"——
最晚出现的左括号，必须最先被闭合。这正是后进先出。

遍历字符串，只做两件事：

    - 遇到左括号：压栈（我还欠着它一个闭合）
    - 遇到右括号：栈顶必须是对应的左括号，然后弹栈
      如果栈是空的，或者栈顶对不上 -> 立刻判定无效

遍历结束后，栈必须为空。栈非空说明还有左括号没被闭合（比如 "((("）。

三个失败场景，各对应一条判断：
    1. "(" -> 遍历完栈没空        -> 有左括号没闭合
    2. ")" -> 遇到右括号时栈为空  -> 右括号多了
    3. "(]" -> 栈顶和右括号不匹配 -> 类型对不上

--------------------------------------------------------------------------
复杂度
--------------------------------------------------------------------------
时间 O(n)：每个字符恰好进栈或出栈一次。
空间 O(n)：最坏情况如 "((((("，栈里存下全部字符。

--------------------------------------------------------------------------
边界用例
--------------------------------------------------------------------------
1. ""          -> True    空字符串视为有效
2. "()"        -> True    最短的有效串
3. "()[]{}"    -> True    多组并列，不嵌套
4. "([{}])"    -> True    多层嵌套
5. "([)]"      -> False   顺序错了——这是最容易漏的一个
6. "((("       -> False   只有左括号
7. ")))"       -> False   只有右括号
8. "("         -> False   单个左括号
9. "]"         -> False   单个右括号
"""


def is_valid(s: str) -> bool:
    """判断括号字符串是否有效。"""
    # 右括号 -> 它需要的左括号
    closer_to_opener = {")": "(", "]": "[", "}": "{"}
    stack: list[str] = []

    for ch in s:
        if ch in "([{":
            stack.append(ch)
        elif ch in closer_to_opener:
            # 栈空（右括号多了）或栈顶对不上（类型/顺序错）都判负
            if not stack or stack.pop() != closer_to_opener[ch]:
                return False
        else:
            # 题目保证只含括号，这里对意外字符显式判负，避免静默放过
            return False

    # 全部闭合才算有效
    return not stack


def main() -> int:
    cases = [
        ("", True),
        ("()", True),
        ("()[]{}", True),
        ("([{}])", True),
        ("([)]", False),
        ("(((", False),
        (")))", False),
        ("(", False),
        ("]", False),
        ("{[]}", True),
    ]

    passed = 0
    print("[2] 有效的括号 (Valid Parentheses)")
    for s, expected in cases:
        actual = is_valid(s)
        ok = actual == expected
        passed += ok
        mark = "PASS" if ok else "FAIL"
        shown = f'"{s}"' if s else "(空字符串)"
        print(f"    [{mark}] s={shown:<12} -> {actual}  期望 {expected}")

    total = len(cases)
    print(f"    通过 {passed}/{total}")
    return 0 if passed == total else 1


if __name__ == "__main__":
    raise SystemExit(main())
