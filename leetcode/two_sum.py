"""
LeetCode 1. 两数之和（Two Sum）—— 难度：简单
https://leetcode.cn/problems/two-sum/

题目
----
给定一个整数数组 nums 和一个整数目标值 target，请你在该数组中找出和为目标值
target 的那两个整数，并返回它们的数组下标。

你可以假设每种输入只会对应一个答案，并且你不能使用两次相同的元素。
你可以按任意顺序返回答案。

--------------------------------------------------------------------------
思路：哈希表 + 一次遍历
--------------------------------------------------------------------------
最直白的做法是两层循环枚举所有配对，时间复杂度 O(n^2)。瓶颈在于：
对每个数，我都在"重新找"它的另一半。

换个角度——对当前数字 n，我真正关心的只有一件事：
目标值减去它还差多少，也就是 complement = target - n。
如果这个 complement 之前出现过，那么当前下标和它记录的下标就是答案。

于是遍历时用一个字典 seen 记下"已经见过的数值 -> 它的下标"：

    1. 算出 complement = target - n
    2. complement 在 seen 里  -> 直接返回 [seen[complement], i]
    3. 不在                    -> 把 n 和下标 i 存进 seen，继续下一个

关键细节：**先查、再存**。
如果写成"先存再查"，遇到 nums = [3, 3], target = 6 时，
下标 0 会和自己匹配上，返回 [0, 0] —— 同一个元素被用了两次，是错的。

--------------------------------------------------------------------------
复杂度
--------------------------------------------------------------------------
时间 O(n)：每个元素只进入字典一次、被查询一次，字典的查找与插入均摊 O(1)。
空间 O(n)：最坏情况下（答案在最后两位）字典需要存下 n-1 个元素。

对比暴力解法的 O(n^2) / O(1)，这是典型的"用空间换时间"。

--------------------------------------------------------------------------
边界用例（这比代码本身更重要）
--------------------------------------------------------------------------
1. [3, 3], 6          -> [0, 1]   重复值；验证"先查再存"的必要性
2. [-3, 4, 3, 90], 0  -> [0, 2]   负数与正数相加得到 0
3. [0, 4, 3, 0], 0    -> [0, 3]   目标值为 0，且两个 0 分处首尾
4. [1, 2], 100        -> []       题目保证有解，但代码留了兜底返回
5. [2, 5, 5, 11], 10  -> [1, 2]   答案里的两个数相等，且不是第一次出现的那个
"""


def two_sum(nums: list[int], target: int) -> list[int]:
    """返回 nums 中和为 target 的两个元素的下标；无解时返回空列表。"""
    seen: dict[int, int] = {}

    for i, n in enumerate(nums):
        complement = target - n

        # 先查：确认另一半是否已经出现过
        if complement in seen:
            return [seen[complement], i]

        # 再存：把自己登记进去，供后面的元素来匹配
        seen[n] = i

    return []


def main() -> int:
    cases = [
        (([2, 7, 11, 15], 9), [0, 1]),
        (([3, 2, 4], 6), [1, 2]),
        (([3, 3], 6), [0, 1]),
        (([-3, 4, 3, 90], 0), [0, 2]),
        (([0, 4, 3, 0], 0), [0, 3]),
        (([2, 5, 5, 11], 10), [1, 2]),
    ]

    passed = 0
    print("[1] 两数之和 (Two Sum)")
    for (nums, target), expected in cases:
        actual = two_sum(nums, target)
        ok = actual == expected
        passed += ok
        mark = "PASS" if ok else "FAIL"
        print(f"    [{mark}] nums={nums} target={target} -> {actual}  期望 {expected}")

    # 兜底分支单独验证：题目保证有解，但代码不该崩
    empty = two_sum([1, 2], 100)
    ok = empty == []
    passed += ok
    print(f"    [{'PASS' if ok else 'FAIL'}] 无解时返回空列表 -> {empty}")

    total = len(cases) + 1
    print(f"    通过 {passed}/{total}")
    return 0 if passed == total else 1


if __name__ == "__main__":
    raise SystemExit(main())
